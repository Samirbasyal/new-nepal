// ========================================
// API - PRIVATE LOAN AGREEMENT FILES (SUPER ADMIN ONLY)
// ========================================
// Addresses:
//   POST /api/admin/loans/agreement              -> upload a scanned agreement
//   GET  /api/admin/loans/agreement?file=...     -> view it
//   GET  /api/admin/loans/agreement?file=...&download=1 -> download it
//
// WHY THIS IS NOT app/api/upload
//   That endpoint is for pictures. A loan agreement carries a name, a
//   signature, an amount and sometimes a citizenship copy, so it must never be
//   public - and it may be a PDF or a Word document, which the picture
//   endpoint refuses. This route has its own allow-list and its own size limit.
//
// WHERE THE FILES GO
//   The choice lives in lib/storage.ts, exactly like the picture uploads:
//   Vercel Blob when a store is connected, otherwise the project's own
//   "private/loans" folder while developing.
//
//   WHAT WENT WRONG BEFORE (and why this file was rewritten)
//     This route used to write straight into private/loans with node:fs. That
//     works on a computer, but on Vercel the disk is READ-ONLY and temporary,
//     so every agreement upload failed with
//         "Uploading files is not possible on this hosting plan"
//     501 message you would have seen in the Admin Panel. Sharing the storage
//     decision with the upload endpoint fixes it: an agreement is now stored
//     permanently, and privately, on the same Blob store.
//
// PRIVATE IN BOTH PLACES
//   A Blob is written with access:'private', so Vercel itself refuses to hand
//   it to anybody who does not hold the store token - the address cannot be
//   shared and opened. A local file lives in a folder the website does not
//   serve. Either way the only way to read one is the GET below, which checks
//   the role again on every single request.
//
// WHAT IS STORED IN THE DATABASE
//   Still "2026/agr-1730000000-a1b2c3d4.pdf", unchanged, so an address saved by
//   an earlier version keeps working. Internally that same name is used as the
//   Blob key, with the prefix "private/loans/" in front of it.
//
// SECURITY
//   - Super Administrator only, checked on the SERVER for both directions.
//   - The stored name is generated by us (never the uploaded file name).
//   - The "file" value must match a strict pattern, so "..\..\" cannot be used
//     to read anything else, and the final path is checked to stay inside the
//     private folder as well.
//   - Nothing is cached and nothing is sniffed.
// ========================================

import { randomBytes } from 'node:crypto';
import { createReadStream } from 'node:fs';
import { mkdir, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { requireSuperAdminApi } from '@/lib/api/guard';
import { fail, ok, serverError } from '@/lib/api/http';
import { writeActivity } from '@/lib/audit';
import {
  isPersistentStorageConfigured,
  storageDescription,
  StorageUnavailableError,
  describeStorageFailure,
  privateBlobWriteOptions,
  privateBlobReadAttempts,
} from '@/lib/storage';

// A scanned agreement is often several pages, so this route must not be cached
// and needs more time than a normal request.
export const dynamic = 'force-dynamic';
export const maxDuration = 30;

// Only documents that make sense for a signed agreement.
const ALLOWED_TYPES: Record<string, string> = {
  'application/pdf': 'pdf',
  'image/jpeg': 'jpg',
  'image/jpg': 'jpg',
  'image/png': 'png',
  'image/webp': 'webp',
  'application/msword': 'doc',
  'application/vnd.openxmlformats-officedocument.wordprocessingml.document': 'docx',
};

const TYPE_BY_EXTENSION: Record<string, string> = {
  pdf: 'application/pdf',
  jpg: 'image/jpeg',
  png: 'image/png',
  webp: 'image/webp',
  doc: 'application/msword',
  docx: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
};

// 10 MB: a scanned agreement is often several pages.
const MAX_BYTES = 10 * 1024 * 1024;

// The prefix that keeps agreements out of the public part of the Blob store.
const BLOB_PREFIX = 'private/loans/';

// The folder used while developing. It is never served by the website and it is
// listed in .gitignore, so an agreement can never be committed to GitHub.
function privateRoot(): string {
  return path.join(process.cwd(), 'private', 'loans');
}

/** A stored name we generated: 2026/agr-1730000000-a1b2c3d4.pdf */
const SAFE_NAME = /^\d{4}\/[a-z0-9-]+\.(pdf|jpg|png|webp|doc|docx)$/;

/** The same name, moved into the private part of the Blob store. */
function blobKeyFor(storedName: string): string {
  return BLOB_PREFIX + storedName;
}

/** True while developing, where writing to the project folder is allowed. */
function isLocalStorageAllowed(): boolean {
  return process.env.NODE_ENV !== 'production';
}

// ========================================
// POST - UPLOAD
// ========================================
export async function POST(request: Request) {
  const auth = await requireSuperAdminApi(request);
  if (!auth.ok) return auth.response;

  let form: FormData;
  try {
    form = await request.formData();
  } catch {
    return fail('No file was received.', 400);
  }

  const file = form.get('file');
  if (!(file instanceof File)) {
    return fail('Please choose the agreement file to upload.', 400);
  }

  const extension = ALLOWED_TYPES[file.type];
  if (!extension) {
    return fail('Please upload a PDF, a picture (JPG, PNG, WEBP) or a Word document.', 415);
  }

  if (file.size > MAX_BYTES) {
    return fail('That file is larger than 10 MB. Please upload a smaller copy.', 413);
  }

  if (file.size === 0) {
    return fail('That file is empty. Please choose it again.', 400);
  }

  const year = String(new Date().getFullYear());
  const safeName = `agr-${Date.now()}-${randomBytes(4).toString('hex')}.${extension}`;
  const storedName = `${year}/${safeName}`;
  const bytes = Buffer.from(await file.arrayBuffer());

  try {
    let provider: 'vercel-blob' | 'local';

    if (isPersistentStorageConfigured()) {
      // Imported here rather than at the top of the file, so the website still
      // runs on a computer where the Blob package has not been installed.
      const { put } = await import('@vercel/blob');

      // THE FIX. The access mode must match what the connected store allows. A
      // store is created as either public or private and can never be changed, so
      // asking a public store for a private file is refused with "Cannot use
      // private access on a public store" - exactly what stopped payment receipts.
      // privateBlobWriteOptions() settles this in ONE place for the whole website.
      const writeOptions = privateBlobWriteOptions();

      await put(blobKeyFor(storedName), bytes, {
        // A private file cannot be opened by whoever happens to hold the link -
        // only through the GET below, which checks the role again.
        ...writeOptions,
        contentType: file.type,
        addRandomSuffix: false,
      });
      provider = 'vercel-blob';
    } else if (isLocalStorageAllowed()) {
      const folder = path.join(privateRoot(), year);
      await mkdir(folder, { recursive: true });
      await writeFile(path.join(folder, safeName), bytes);
      provider = 'local';
    } else {
      throw new StorageUnavailableError();
    }

    await writeActivity({
      actorId: auth.user.id,
      actorName: auth.user.name,
      action: 'CREATE',
      entity: 'Loan agreement',
      detail: `uploaded ${file.name} (${Math.round(file.size / 1024)} KB)`,
    });

    // The address the Admin Panel stores on the loan and shows as a button.
    // It is NOT a public file - opening it runs the GET below, which checks the
    // role again.
    return ok(
      {
        url: `/api/admin/loans/agreement?file=${encodeURIComponent(storedName)}`,
        storedName,
        originalName: file.name,
        size: file.size,
        type: file.type,
        storage: provider,
        // True when the document is on permanent storage. The screen can warn
        // when it is not, so nobody is surprised at the next deployment.
        permanent: provider === 'vercel-blob',
      },
      201,
      provider === 'vercel-blob'
        ? 'The agreement was uploaded and stored permanently. Please save the loan to keep it.'
        : 'The agreement was uploaded to this computer only. It will not survive a redeploy - connect Vercel Blob before going live.',
    );
  } catch (error) {
    // ---------- Nowhere permanent to put it ----------
    // 501 means "this server cannot do that yet", which is very different from
    // "your request was wrong". The message tells the owner exactly what to set.
    if (error instanceof StorageUnavailableError) {
      console.error('[loan-agreement] no storage configured:', storageDescription());
      return fail(error.message, 501);
    }

    // An actionable sentence instead of the storage provider's raw text.
    console.error('[loan-agreement] storage failure:', error);
    const friendly = describeStorageFailure(error);
    return fail(friendly.message, friendly.status);
  }
}

// ========================================
// GET - VIEW OR DOWNLOAD
// ========================================
export async function GET(request: Request) {
  // Both directions are protected: without this check the document would be as
  // public as any picture on the website.
  const auth = await requireSuperAdminApi(request);
  if (!auth.ok) return auth.response;

  const url = new URL(request.url);
  const requested = url.searchParams.get('file') ?? '';
  const asDownload = url.searchParams.get('download') === '1';

  // Strict pattern first: this alone blocks ".." and absolute paths.
  if (!SAFE_NAME.test(requested)) {
    return fail('That agreement file was not found.', 404);
  }

  const fileName = requested.split('/').pop() ?? 'agreement';
  const extension = requested.split('.').pop() ?? '';
  const contentType = TYPE_BY_EXTENSION[extension] ?? 'application/octet-stream';

  const headers: Record<string, string> = {
    // inline = show it in the browser, attachment = save it.
    'Content-Disposition': `${asDownload ? 'attachment' : 'inline'}; filename="${fileName}"`,
    // Never let a shared computer or a proxy keep a copy of somebody's loan
    // agreement.
    'Cache-Control': 'private, no-store, max-age=0',
    'X-Content-Type-Options': 'nosniff',
  };

  // ---------- Vercel Blob ----------
  if (isPersistentStorageConfigured()) {
    try {
      const { get } = await import('@vercel/blob');

      // Try the private store first, then the connected store, so an agreement
      // already on file keeps working even if a private store is added later.
      for (const attempt of privateBlobReadAttempts()) {
        try {
          const result = await get(blobKeyFor(requested), {
            access: attempt.access,
            ...(attempt.storeId ? { storeId: attempt.storeId } : {}),
            ...(attempt.token ? { token: attempt.token } : {}),
          });

          if (result && result.stream) {
            return new Response(result.stream as unknown as ReadableStream, {
              status: 200,
              headers: {
                ...headers,
                'Content-Type': result.blob?.contentType ?? contentType,
              },
            });
          }
        } catch (error) {
          // A missing blob and a storage problem look the same to the reader, and
          // neither should ever leak the store token or a stack trace.
          console.error('[loan-agreement] could not read the file:', error);
        }
      }

      return fail('That agreement file was not found on this server.', 404);
    } catch (error) {
      console.error('[loan-agreement] unexpected read failure:', error);
      return fail('That agreement file was not found on this server.', 404);
    }
  }

  // ---------- Local disk (development) ----------
  const absolute = path.join(privateRoot(), requested);

  // Second guard: whatever happens, the path must stay inside the private
  // folder. Two checks are cheap and this is somebody's signed document.
  const rootWithSeparator = privateRoot() + path.sep;
  if (!path.resolve(absolute).startsWith(path.resolve(rootWithSeparator))) {
    return fail('That agreement file was not found.', 404);
  }

  try {
    const info = await stat(absolute);
    if (!info.isFile()) return fail('That agreement file was not found.', 404);

    const stream = createReadStream(absolute);
    const body = new ReadableStream({
      start(controller) {
        stream.on('data', (chunk) => controller.enqueue(new Uint8Array(chunk as Buffer)));
        stream.on('end', () => controller.close());
        stream.on('error', (error) => controller.error(error));
      },
      cancel() {
        stream.destroy();
      },
    });

    return new Response(body, {
      status: 200,
      headers: {
        ...headers,
        'Content-Type': contentType,
        'Content-Length': String(info.size),
      },
    });
  } catch {
    // The most likely cause is simply that the file was never uploaded on this
    // computer (for example the database was copied from somewhere else).
    return fail('That agreement file was not found on this server.', 404);
  }
}

